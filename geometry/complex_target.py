"""Model 2's target: a fitted GHD complex as [z, affine in the ostium frame] (TASK §5.6).

The placed fit (image space, mm) is
    V_img = k * exp(l) * V_can(phi) @ Q + b
with V_can the GHD reconstruction of phi in normalised canonical space, exp(l) the fit's scale
(generated by the Stage-1 VAE together with phi), and from the fit and the Stage-1 alignment
(V_img = (V_fit - t_al) @ R_al / s_al, V_fit = (exp(l) V_can Rw^T + t_vec) * norm_canonical):
    Q = Rw^T @ R_al,   k = norm_canonical / s_al,   b = (t_vec * norm_canonical - t_al) @ R_al / s_al.
In the ostium frame (centre C, rows R = [e1; e2; n], scale s):
    V_loc = R (V_img - C) / s = (k exp(l) / s) * V_can @ (Q R^T) + R (b - C) / s
so the affine is rotation Q R^T (stored as 6 numbers: its first two columns), log(k / s) and
R (b - C) / s: 10 numbers. It does not change under a global rotation of the scene.
"""
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
ASSEMBLED = REPO / "runtime_dataset" / "assembled"


def rodrigues(w):
    w = np.asarray(w, float)
    th = np.linalg.norm(w)
    if th < 1e-12:
        return np.eye(3)
    k = w / th
    K = np.array([[0, -k[2], k[1]], [k[2], 0, -k[0]], [-k[1], k[0], 0]])
    return np.eye(3) + np.sin(th) * K + (1 - np.cos(th)) * K @ K


def fit_parts(case, dataset, norm_canonical):
    """phi (144, 3), l (log scale), Q, k, b of a case's placed fit."""
    d = ASSEMBLED / dataset / case
    G = np.load(d / "ghd_coefficients.npz", allow_pickle=True)
    al = np.load(d / "alignment_result.npy", allow_pickle=True).item()
    R_al, s_al, t_al = np.asarray(al["R"], float), float(al["s"]), np.asarray(al["t"], float)
    Rw = rodrigues(G["w_rot"])
    Q = Rw.T @ R_al
    k = float(norm_canonical) / s_al
    b = (np.asarray(G["t_vec"], float) * float(norm_canonical) - t_al) @ R_al / s_al
    return dict(phi=np.asarray(G["phi"], float).reshape(-1, 3), log_scale=float(np.asarray(G["log_scale"])),
                Q=Q, k=k, b=b)


def placed(V_can, log_scale, Q, k, b):
    return k * np.exp(log_scale) * np.asarray(V_can) @ Q + b


def rot6d(M):
    return np.concatenate([M[:, 0], M[:, 1]])


def rot_from_6d(v):
    """Gram-Schmidt: 6 numbers -> rotation matrix (columns m1, m2, m1 x m2)."""
    v = np.asarray(v, float)
    a1, a2 = v[:3], v[3:6]
    m1 = a1 / np.linalg.norm(a1)
    m2 = a2 - (a2 @ m1) * m1
    m2 /= np.linalg.norm(m2)
    return np.stack([m1, m2, np.cross(m1, m2)], axis=1)


def affine_in_frame(Q, k, b, C, R, s):
    """(Q, k, b) of a placed fit -> the 10-number affine in the ostium frame (C, R rows, s)."""
    return np.concatenate([rot6d(Q @ R.T), [np.log(k / s)], R @ (np.asarray(b) - C) / s])


def place_from_frame(V_can, log_scale, affine, C, R, s):
    """Inverse: canonical vertices + the 10-number affine + the ostium frame -> image space."""
    M = rot_from_6d(affine[:6])
    loc = np.exp(affine[6]) * np.exp(log_scale) * np.asarray(V_can) @ M + affine[7:10]
    return C + s * loc @ R


def rotate_scene(Q, b, G):
    """A global rotation x -> G x of the scene: the placed fit's Q and b in the rotated scene."""
    return Q @ G.T, np.asarray(b) @ G.T
